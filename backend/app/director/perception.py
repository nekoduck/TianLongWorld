"""
[INPUT]: 依赖标准库 re
[OUTPUT]: 对外提供 surface() —— 玩家动作中外人看得见、听得见的部分
[POS]: director 的感知边界：同一条动作文本，导演全读，NPC 与规则层只读"表面行为"。
       被 lethal.judge（只有看得见的冒犯才招来杀身之祸）与 pipeline 的 JIT 点名检索（内心念头不把历史拽进上下文）共用，
       "玩家的表面行为"在全系统只有这一个定义
[PROTOCOL]: 变更时更新此头部，然后检查 CLAUDE.md
"""

import re

# 只收纯心理动词：从标记起到句读为止都是念头。"暗自""暗中""默默"不收——"暗自一掌拍向乔峰后心"是看得见的偷袭
_THOUGHT = re.compile(
    r"(心里|心中|心想|心道|心下|暗想|暗忖|暗骂|寻思|思忖|盘算|琢磨|默念|腹诽)[^，。；！？,.;!?\n]*"
)


def surface(action: str) -> str:
    """剥掉内心念头的从句："心想管他的，一拳打在乔峰脸上" → "，一拳打在乔峰脸上"。"""
    return _THOUGHT.sub("", action)
